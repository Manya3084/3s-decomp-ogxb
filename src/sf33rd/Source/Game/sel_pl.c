void Auto_Repeat_Sub(s16 PL_id) {
    u16 sw;

    if (Demo_Flag == 0) {
        return;
    }

    if (Cursor_Move[PL_id]) {
        return;
    }

    if (PL_id == 0) {
        sw = p1sw_0;
    } else {
        sw = p2sw_0;
    }

    sw = Disposal_Of_Diagonal(sw);

    switch (Auto_No[PL_id]) {
    case 0:
        if (sw & 8) {
            Auto_No[PL_id] = 1;
            Auto_Cursor[PL_id] = 8;
            Auto_Timer[PL_id] = Repeat_Time_Data[0];
            Auto_Index[PL_id] = 1;
            break;
        }

        if (sw & 4) {
            Auto_No[PL_id] = 1;
            Auto_Cursor[PL_id] = 4;
            Auto_Timer[PL_id] = Repeat_Time_Data[0];
            Auto_Index[PL_id] = 1;
            break;
        }

        if (sw & 1) {
            Auto_No[PL_id] = 1;
            Auto_Cursor[PL_id] = 1;
            Auto_Timer[PL_id] = Repeat_Time_Data[0];
            Auto_Index[PL_id] = 1;
            break;
        }

        if (sw & 2) {
            Auto_No[PL_id] = 1;
            Auto_Cursor[PL_id] = 2;
            Auto_Timer[PL_id] = Repeat_Time_Data[0];
            Auto_Index[PL_id] = 1;
        }

        break;

    case 1:
        if (sw != Auto_Cursor[PL_id]) {
            Auto_No[PL_id] = 0;
            break;
        }

        if (Auto_Timer[PL_id] -= 1) {
            break;
        }

        Auto_Timer[PL_id] = Repeat_Time_Data[Auto_Index[PL_id]];
        Auto_Index[PL_id]++;

        if (Auto_Index[PL_id] > 2) {
            Auto_Index[PL_id] = 2;
        }

        if (sw & 8) {
            Sel_PL_Sub_CR(PL_id);
        }

        if (sw & 4) {
            Sel_PL_Sub_CL(PL_id);
        }

        if (sw & 1) {
            Sel_PL_Sub_CU(PL_id);
        }

        if (sw & 2) {
            Sel_PL_Sub_CD(PL_id);
        }

        break;
    }
}

u16 Auto_Repeat_Sub_Wife(s16 PL_id) {
    u16 sw;

    if (Cursor_Move[PL_id] || Demo_Flag == 0) {
        return 0;
    }

    if (PL_id == 0) {
        sw = p1sw_0;
    } else {
        sw = p2sw_0;
    }

    switch (Auto_No[PL_id]) {
    case 0:
        if (sw & 1) {
            Auto_No[PL_id] = 1;
            Auto_Cursor[PL_id] = 1;
            Auto_Timer[PL_id] = Repeat_Time_Data_Wife[0];
            Auto_Index[PL_id] = 1;
        } else if (sw & 2) {
            Auto_No[PL_id] = 1;
            Auto_Cursor[PL_id] = 2;
            Auto_Timer[PL_id] = Repeat_Time_Data_Wife[0];
            Auto_Index[PL_id] = 1;
        }

        break;

    case 1:
        if (sw &= Auto_Cursor[PL_id]) {
            if (Auto_Timer[PL_id] -= 1) {
                break;
            }

            Auto_Timer[PL_id] = Repeat_Time_Data_Wife[Auto_Index[PL_id]++];

            if (Auto_Index[PL_id] > 2) {
                Auto_Index[PL_id] = 2;
            }

            if (sw & 1) {
                return 1;
            }

            if (sw & 2) {
                return 2;
            }

            break;
        }

        Auto_No[PL_id] = 0;
        break;
    }

    return 0;
}

