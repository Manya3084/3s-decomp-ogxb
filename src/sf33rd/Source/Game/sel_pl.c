u16 Disposal_Of_Diagonal(u16 sw) {
    sw = sw & 0xF;

    if (sw == 1) {
        return 1;
    }

    if (sw == 2) {
        return 2;
    }

    if (sw == 9) {
        return 1;
    }

    if (sw == 6) {
        return 2;
    }

    return sw &= 0xC;
}

